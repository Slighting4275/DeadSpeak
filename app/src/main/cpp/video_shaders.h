static const char *const DS_AUDIO_WAVE_FRAGMENT_SHADER =
    "precision mediump float;\n"
    "uniform float u_time;\n"
    "uniform float u_amp;\n"
    "uniform float u_bands[8];\n"
    "uniform float u_bands16[16];\n"
    "uniform float u_peaks[8];\n"
    "uniform vec3 u_color;\n"
    "uniform int u_theme;\n"
    "uniform int u_mode;\n"
    "varying vec2 v_uv;\n"
    "void main() {\n"
    "    float x = v_uv.x;\n"
    "    if (u_mode == 2) {\n" /* Siri 16-band multi-harmonic ribbon mode */
    "        float b16 = clamp(x * 15.0, 0.0, 14.999);\n"
    "        int bi0 = int(floor(b16));\n"
    "        float bfrac = b16 - float(bi0);\n"
    "        float e0 = 0.0;\n"
    "        float e1 = 0.0;\n"
    "        for (int i = 0; i < 16; ++i) {\n"
    "            if (i == bi0) e0 = u_bands16[i];\n"
    "            if (i == bi0 + 1) e1 = u_bands16[i];\n"
    "        }\n"
    "        float mag = mix(e0, e1, bfrac);\n"
    "        float ny = (v_uv.y - 0.5) * 2.0;\n"
    "        float env = sin(x * 3.14159265);\n"
    "        float drive = clamp(0.14 + u_amp * 0.55 + mag * 0.72, 0.08, 0.96) * env;\n"
    "        float c_axis = exp(-abs(ny) * 52.0) * 0.75;\n"
    "        vec3 sum = vec3(1.0, 1.0, 1.0) * c_axis;\n"
    "        float a_tot = c_axis;\n"
    "        for (int k = 0; k < 5; ++k) {\n"
    "            float fk = float(k);\n"
    "            float phase = u_time * (5.2 + fk * 1.9) + fk * 1.35;\n"
    "            float freq = 10.0 + fk * 7.5;\n"
    "            float curve = sin(x * freq + phase) * drive * (1.0 - fk * 0.14);\n"
    "            float glow = exp(-abs(ny - curve) * (15.0 + fk * 2.0));\n"
    "            vec3 tint = (k == 0) ? u_color : (k == 1 ? vec3(0.25, 0.95, 1.0) : (k == 2 ? vec3(0.85, 0.35, 1.0) : (k == 3 ? vec3(0.25, 1.0, 0.65) : vec3(1.0, 0.70, 0.25))));\n"
    "            sum += tint * glow * (0.68 - fk * 0.08);\n"
    "            a_tot += glow * 0.45;\n"
    "        }\n"
    "        gl_FragColor = vec4(clamp(sum, 0.0, 1.0), clamp(a_tot, 0.0, 0.94));\n"
    "        return;\n"
    "    }\n"
    "    if (u_mode == 1) {\n"
    "        float col_f = clamp(x * 8.0, 0.0, 7.999);\n"
    "        int bi = int(floor(col_f));\n"
    "        float cell_x = fract(col_f);\n"
    "        float lvl = 0.0;\n"
    "        float pk = 0.0;\n"
    "        for (int i = 0; i < 8; ++i) {\n"
    "            if (i == bi) { lvl = u_bands[i]; pk = u_peaks[i]; }\n"
    "        }\n"
    "        float in_col = step(0.14, cell_x) * (1.0 - step(0.86, cell_x));\n"
    "        float seg = fract(v_uv.y * 10.0);\n"
    "        float in_seg = step(0.16, seg);\n"
    "        float lit = step(v_uv.y, clamp(lvl, 0.03, 0.96)) * in_col * in_seg;\n"
    "        float cap = exp(-abs(v_uv.y - clamp(pk, 0.05, 0.96)) * 42.0) * in_col;\n"
    "        vec3 hi = (u_theme == 1) ? vec3(0.25, 1.0, 0.70) : vec3(1.0, 0.45, 0.15);\n"
    "        vec3 bar_col = mix(u_color, hi, smoothstep(0.55, 0.95, v_uv.y));\n"
    "        vec3 bg = vec3(0.08, 0.13, 0.12) * in_col * in_seg;\n"
    "        vec3 out_col = mix(bg, bar_col, lit) + vec3(0.95, 1.0, 0.90) * cap;\n"
    "        float alpha = clamp(0.24 * in_col * in_seg + lit * 0.90 + cap * 0.92, 0.0, 0.95);\n"
    "        gl_FragColor = vec4(clamp(out_col, 0.0, 1.0), alpha);\n"
    "        return;\n"
    "    }\n"
    "    float y = (v_uv.y - 0.5) * 2.0;\n"
    "    float idx = clamp(x * 7.0, 0.0, 6.999);\n"
    "    int i0 = int(floor(idx));\n"
    "    float frac = idx - float(i0);\n"
    "    float b0 = 0.0;\n"
    "    float b1 = 0.0;\n"
    "    for (int i = 0; i < 8; ++i) {\n"
    "        if (i == i0) b0 = u_bands[i];\n"
    "        if (i == i0 + 1) b1 = u_bands[i];\n"
    "    }\n"
    "    float band_energy = mix(b0, b1, frac);\n"
    "    float env = sin(x * 3.14159265);\n"
    "    float gain = clamp(0.10 + u_amp * 0.70 + band_energy * 0.65, 0.06, 0.92) * env;\n"
    "    float w1 = sin(x * 18.0 + u_time * 6.5) * 0.55 * gain;\n"
    "    float w2 = sin(x * 31.0 - u_time * 9.0 + 1.4) * 0.40 * gain;\n"
    "    float w3 = sin(x * 46.0 + u_time * 12.0 + 2.8) * 0.25 * gain;\n"
    "    float g1 = exp(-abs(y - w1) * 16.0);\n"
    "    float g2 = exp(-abs(y - w2) * 14.0);\n"
    "    float g3 = exp(-abs(y - w3) * 18.0);\n"
    "    float axis = exp(-abs(y) * 42.0) * 0.28;\n"
    "    vec3 col1 = u_color;\n"
    "    vec3 col2 = (u_theme == 1) ? vec3(0.2, 1.0, 0.55) : vec3(0.3, 0.8, 1.0);\n"
    "    vec3 col3 = (u_theme == 2) ? vec3(0.65, 0.45, 1.0) : vec3(1.0, 0.65, 0.25);\n"
    "    vec3 sum = col1 * g1 + col2 * g2 * 0.75 + col3 * g3 * 0.65 + vec3(0.85, 0.98, 0.92) * axis;\n"
    "    float alpha = clamp(g1 * 0.85 + g2 * 0.60 + g3 * 0.50 + axis, 0.0, 0.92);\n"
    "    gl_FragColor = vec4(clamp(sum, 0.0, 1.0), alpha);\n"
    "}\n";

#endif /* DEADSPEAK_VIDEO_SHADERS_H */
